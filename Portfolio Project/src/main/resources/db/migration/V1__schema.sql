-- Schema: portable between PostgreSQL (production) and H2 in PostgreSQL mode (local dev/tests).

CREATE TABLE profile (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name          VARCHAR(120)  NOT NULL,
    title              VARCHAR(160)  NOT NULL,
    tagline            VARCHAR(300)  NOT NULL,
    bio                VARCHAR(4000) NOT NULL,
    location           VARCHAR(120),
    email              VARCHAR(254)  NOT NULL,
    github_url         VARCHAR(300),
    linkedin_url       VARCHAR(300),
    years_experience   INT NOT NULL,
    projects_completed INT NOT NULL,
    happy_clients      INT NOT NULL
);

CREATE TABLE skill (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(80) NOT NULL,
    category      VARCHAR(60) NOT NULL,
    level         INT NOT NULL CHECK (level BETWEEN 0 AND 100),
    display_order INT NOT NULL
);

CREATE TABLE project (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title         VARCHAR(120)  NOT NULL,
    summary       VARCHAR(1000) NOT NULL,
    tech_stack    VARCHAR(300)  NOT NULL,
    repo_url      VARCHAR(300),
    live_url      VARCHAR(300),
    featured      BOOLEAN NOT NULL DEFAULT FALSE,
    display_order INT NOT NULL
);

CREATE TABLE testimonial (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author        VARCHAR(120)  NOT NULL,
    role          VARCHAR(160)  NOT NULL,
    quote         VARCHAR(1000) NOT NULL,
    display_order INT NOT NULL
);

CREATE TABLE contact_message (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(100)  NOT NULL,
    email      VARCHAR(254)  NOT NULL,
    subject    VARCHAR(150)  NOT NULL,
    message    VARCHAR(3000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    is_read    BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX idx_contact_message_created_at ON contact_message (created_at);
